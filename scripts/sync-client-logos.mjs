#!/usr/bin/env node
/**
 * Writes src/data/clientLogoFiles.ts from the .svg and .png files in public/clients/.
 *
 * Why a generated list: SiteFooter (and so the client strip) is imported by at
 * least one client component (src/app/faq/FaqContent.tsx), so the strip cannot
 * read the file system at render time. Runs in prebuild; run it by hand after
 * adding a logo. Missing folder = empty list = text wordmarks everywhere.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'public', 'clients');
const out = join(root, 'src', 'data', 'clientLogoFiles.ts');

const files = existsSync(dir)
  ? readdirSync(dir).filter((f) => /^[a-z0-9-]+\.(svg|png)$/.test(f)).sort()
  : [];

const body = `// Generated by scripts/sync-client-logos.mjs from the files in public/clients/.
// Do not edit by hand; add or remove a logo file and re-run the script.
export const CLIENT_LOGO_FILES: ReadonlyArray<string> = [${files.map((f) => `'${f}'`).join(', ')}];
`;

const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
if (current !== body) writeFileSync(out, body);
console.log(`client logos: ${files.length ? files.join(', ') : 'none (text wordmarks)'}`);
